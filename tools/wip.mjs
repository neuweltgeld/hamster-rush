import puppeteer from 'puppeteer-core';
const base = process.argv[2] || 'http://127.0.0.1:5201/';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--enable-unsafe-swiftshader'], headless: true });
const p = await b.newPage(); await p.setViewport({ width: 1000, height: 600 });
const errs = []; p.on('pageerror', (e) => errs.push('PAGEERR ' + e.message)); p.on('console', (m) => { if (['error'].includes(m.type())) errs.push(m.type() + ' ' + m.text()); });
await p.goto(base + '?bot=1&god=1&autoplay=1&nodegrade=1'); await sleep(4500);
const ev = (f) => p.evaluate(f);
console.log(await ev(() => { const g = window.__hr; for (const id of ['blades','wave','bomb','lightning','flame','bees']) g.addWeapon(id, 5); g.t = 40; return g.weapons.length; }));
await sleep(7000); await p.screenshot({ path: '/workspace/wip-1.png' });
console.log(await ev(() => { const g = window.__hr; g.t = 93; return g.t; }));
await sleep(14000); await p.screenshot({ path: '/workspace/wip-2.png' });
console.log(await ev(() => { const g = window.__hr; return { t: g.t, en: g.en.length, boss: g.bosses?.length }; }));
await ev(() => { window.__botOff && window.__botOff(); const g = window.__hr; g.gainXp(9999, true); });
await sleep(1800); await p.screenshot({ path: '/workspace/wip-3.png' });
await ev(() => { const g = window.__hr; g.t = 150; });
await sleep(1);
await p.evaluate(() => document.querySelector('.card, .lv-card, [data-card]')?.click());
await sleep(5000); await p.screenshot({ path: '/workspace/wip-4.png' });
console.log(errs.slice(0, 10).join('\n') || 'no errors');
await b.close();
